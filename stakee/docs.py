"""Generate the wiki pages under ``models/`` from each family's manifest and module docstring.

``models/README.md`` is the catalogue; ``models/<module>/README.md`` is one page per family
with its design notes, a parts table and print notes; ``models/index.json`` lists the families
for the docs site (parts are in each ``models/<module>/manifest.json``). All of them are
rewritten on every build, so edit the module docstring, ``stakee/families.py`` or the
``PartInfo`` in the module instead.
"""

import ast
import json
import re
from pathlib import Path

from stakee.export import MODELS, ROOT, read_manifest
from stakee.families import FAMILIES, Family

GENERATED = "<!-- Generated by `uv run stakee-build`. Edit the generator, not this file. -->"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _md(text: str) -> str:
    """reStructuredText-style ``literals`` from docstrings as Markdown `literals`."""
    return re.sub(r"``(.+?)``", r"`\1`", text)


def module_docstring(module: str) -> str:
    """The module docstring of ``stakee/modules/<module>.py``, read without importing it."""
    source = ROOT / "stakee" / "modules" / f"{module}.py"
    doc = ast.get_docstring(ast.parse(source.read_text()))
    if not doc:
        raise ValueError(f"{source}: module has no docstring; it becomes the family's wiki page")
    return doc


def _local(part: dict, kind: str) -> str:
    """Path of one exported file relative to its family folder (drops ``models/<module>/``)."""
    return Path(*Path(part["files"][kind]).parts[2:]).as_posix()


def _size(part: dict) -> str:
    return " × ".join(f"{v:g}" for v in part["size_mm"])


def _parts_table(parts: list[dict]) -> list[str]:
    lines = [
        "| Preview | Part | Size (mm) | Material | Download |",
        "| --- | --- | --- | --- | --- |",
    ]
    for p in parts:
        img = f'<img src="{_local(p, "svg")}" width="140" alt="{_cell(p["title"])}">'
        name = f"**{_cell(p['title'])}**<br>{_cell(p['blurb'])}"
        files = f"[STL]({_local(p, 'stl')}) · [STEP]({_local(p, 'step')})"
        lines.append(f"| {img} | {name} | {_size(p)} | {_cell(p['material'])} | {files} |")
    return lines


def _print_notes(parts: list[dict]) -> list[str]:
    """One bullet per distinct note, naming every part that shares it."""
    grouped: dict[str, list[str]] = {}
    for p in parts:
        grouped.setdefault(" ".join(p["print_notes"].split()), []).append(p["title"])
    return [f"- **{', '.join(titles)}**: {note}" for note, titles in grouped.items()]


def family_page(item: Family, parts: list[dict]) -> str:
    lines = [
        GENERATED,
        "",
        f"# {item.title}",
        "",
        item.summary,
        "",
        f"[All models](../README.md) · {len(parts)} parts · "
        f"rebuild with `uv run stakee-build --only {item.module}` · "
        f"source: [`stakee/modules/{item.module}.py`](../../stakee/modules/{item.module}.py)",
        "",
        "## Parts",
        "",
        *_parts_table(parts),
        "",
        "## Print notes",
        "",
        *_print_notes(parts),
        "",
        "## How it works",
        "",
        _md(module_docstring(item.module)),
        "",
    ]
    return "\n".join(lines)


def catalogue_page(families: list[tuple[Family, list[dict]]]) -> str:
    lines = [
        GENERATED,
        "",
        "# Models",
        "",
        "Every family below is generated from the same geometry contract "
        "([`stakee/core.py`](../stakee/core.py)): any part stacks on any crate of the same "
        "footprint. Open a family for its parts, sizes, print notes and STL/STEP files.",
        "",
        "| Preview | Family | What it is | Parts |",
        "| --- | --- | --- | --- |",
    ]
    for item, parts in families:
        first = parts[0]
        img = (
            f'<img src="{item.module}/{_local(first, "svg")}" width="120" '
            f'alt="{_cell(first["title"])}">'
        )
        link = f"[**{item.title}**]({item.module}/README.md)"
        lines.append(f"| {img} | {link} | {_cell(item.summary)} | {len(parts)} |")
    lines.append("")
    return "\n".join(lines)


def index_json(families: list[tuple[Family, list[dict]]]) -> str:
    """Families in catalogue order, with the docstring that explains each one."""
    entries = [
        {
            "module": item.module,
            "title": item.title,
            "summary": item.summary,
            "description": _md(module_docstring(item.module)),
            "manifest": f"models/{item.module}/manifest.json",
            "parts": len(parts),
        }
        for item, parts in families
    ]
    return json.dumps({"families": entries}, indent=2, ensure_ascii=False) + "\n"


def write_docs() -> list[Path]:
    """Rewrite models/index.json, models/README.md and every family's README.md."""
    built: list[tuple[Family, list[dict]]] = []
    written: list[Path] = []
    for item in FAMILIES:
        parts = list(read_manifest(item.module).values())
        if not parts:
            continue
        page = MODELS / item.module / "README.md"
        page.write_text(family_page(item, parts))
        written.append(page)
        built.append((item, parts))
    if not built:
        raise SystemExit(f"no manifests under {MODELS}; run `uv run stakee-build` first")
    index = MODELS / "README.md"
    index.write_text(catalogue_page(built))
    catalogue = MODELS / "index.json"
    catalogue.write_text(index_json(built))
    return [catalogue, index, *written]
