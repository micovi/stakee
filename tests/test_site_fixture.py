"""Drift guard for the docs site's TypeScript port of the box geometry.

`site/src/lib/geometry.ts` re-implements the formulas the configurator shows. This test computes
the same numbers with the Python code into `site/src/lib/geometry.fixture.json`, and
`site/src/lib/geometry.test.ts` checks the port against that file. The site build stays
Python-free; a change here that is not mirrored in the fixture fails this test.
"""

import json
import os
from pathlib import Path

from stakee.cli import (
    MAX_UNITS,
    TILE_CLEARANCE,
    TILE_TEXT_MARGIN,
    compartment_sizes,
    rail_positions,
)
from stakee.core import HEIGHT_UNIT, BoxSize, label_width

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "site" / "src" / "lib" / "geometry.fixture.json"
UPDATE_ENV = "STAKEE_UPDATE_FIXTURES"
REGENERATE = f"{UPDATE_ENV}=1 uv run pytest tests/test_site_fixture.py"

FOOTPRINT_UNITS = (1, 2, 3, 8)
HEIGHTS = (2, 3, 6, 40)


def box_entry(size: BoxSize) -> dict:
    tile_width = label_width(size.width) - 2 * TILE_CLEARANCE
    return {
        "size": [size.nx, size.ny, size.h],
        "outer_mm": [size.width, size.depth, size.lip_top],
        "cavity_mm": list(size.cavity),
        "stack_pitch_mm": size.h * HEIGHT_UNIT,
        "label_text_width_mm": tile_width - 2 * TILE_TEXT_MARGIN,
    }


def divider_entries(units: int) -> list[dict]:
    span = BoxSize(units, units, 3).cavity[0]
    entries = []
    for compartments in range(1, 2 * units + 1):
        rails = rail_positions(units, compartments)
        entries.append(
            {
                "units": units,
                "compartments": compartments,
                "span_mm": span,
                "rails_mm": rails,
                "sizes_mm": compartment_sizes(span, rails),
            }
        )
    return entries


def render_fixture() -> str:
    boxes = [
        box_entry(BoxSize(nx, ny, h))
        for nx in FOOTPRINT_UNITS
        for ny in FOOTPRINT_UNITS
        for h in HEIGHTS
    ]
    dividers = [entry for units in range(1, MAX_UNITS + 1) for entry in divider_entries(units)]

    def rows(entries: list[dict]) -> str:
        return ",\n".join(f"    {json.dumps(entry)}" for entry in entries)

    comment = json.dumps(f"Generated by tests/test_site_fixture.py; run {REGENERATE}")
    return (
        "{\n"
        f'  "comment": {comment},\n'
        f'  "boxes": [\n{rows(boxes)}\n  ],\n'
        f'  "dividers": [\n{rows(dividers)}\n  ]\n'
        "}\n"
    )


def test_site_geometry_fixture_matches_python():
    expected = render_fixture()
    if os.environ.get(UPDATE_ENV) == "1":
        FIXTURE.write_text(expected)
    current = FIXTURE.read_text() if FIXTURE.exists() else ""
    assert current == expected, (
        f"{FIXTURE.relative_to(ROOT)} does not match stakee/core.py and stakee/cli.py. "
        f"Regenerate it with `{REGENERATE}`, then update site/src/lib/geometry.ts until "
        "`bun run test` in site/ passes."
    )
